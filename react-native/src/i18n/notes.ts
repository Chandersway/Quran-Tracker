export type NoteLabels = {
  [K in Exclude<keyof typeof notesWords.en, 'scopeLabel' | 'tagSuggestions'>]: string;
} & { scopeLabel: Record<NoteScope, string>; tagSuggestions: readonly string[] };

export function useNotesCopy(language: Locale): NoteLabels {
  const { t } = useI18n();
  return {
    ...restoreSourceCopy(
      language,
      notesWords[language] ?? notesWords.en,
      notesWords.en,
      screenSourceKeys.notes,
    ),
    tagSuggestions: [0, 1, 2, 3, 4, 5].map((index) => t(`notes.tagCategories.${index}`)),
  };
}
