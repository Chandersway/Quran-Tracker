/** Preserve original Kotlin surah artwork and the validated Warsh source verbatim. */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseWarshMushafResponse, printedWarshPageAyahs } from '../src/domain/selectableWarsh';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha256 = (value: Buffer | string) => createHash('sha256').update(value).digest('hex');
const write = (name: string, value: string) => writeFileSync(path.join(root, name), value, 'utf8');
const pictures = 'assets/surah-cards';
mkdirSync(path.join(root, pictures), { recursive: true });
const illustrations: Record<string, { sha256: string; bytes: number }> = {};
const imageLoaders = [
  '// Generated by scripts/prepare-reader-assets.ts. Original Kotlin artwork, unchanged.',
  '/* eslint-disable @typescript-eslint/no-require-imports -- Static Metro image assets must use require. */',
  "import type { ImageSourcePropType } from 'react-native';",
  'export const surahIllustrations: Record<number, ImageSourcePropType> = {',
];
for (let surah = 1; surah <= 114; surah++) {
  const name = `surah_card_${String(surah).padStart(3, '0')}.jpg`;
  const source = path.resolve(root, '../app/src/main/res/drawable', name);
  const bytes = readFileSync(source);
  copyFileSync(source, path.join(root, pictures, name));
  illustrations[name] = { sha256: sha256(bytes), bytes: bytes.length };
  imageLoaders.push(`  ${surah}: require('../../../../${pictures}/${name}'),`);
}
imageLoaders.push('};', '');
write('src/features/quran/model/surahIllustrations.ts', imageLoaders.join('\n'));
write(
  `${pictures}/provenance.json`,
  JSON.stringify({ source: '../app/src/main/res/drawable', files: illustrations }, null, 2) + '\n',
);

const sourceUrl =
  'https://text.quran.ws/download?edition=warsh&by=word&format=json&fields=surah,ayah,page,line,position,number&signs=attached&header=false';
async function prepareWarsh() {
  const sourceArg = process.argv.indexOf('--source');
  const source =
    sourceArg >= 0
      ? readFileSync(path.resolve(root, process.argv[sourceArg + 1]!))
      : Buffer.from(
          await (async () => {
            const response = await fetch(sourceUrl, {
              headers: {
                Accept: 'application/json',
                'User-Agent': 'Quran-Tracker content preparation',
              },
            });
            if (!response.ok) throw new Error(`Warsh source unavailable (${response.status})`);
            return response.arrayBuffer();
          })(),
        );
  const corpus = JSON.parse(source.toString('utf8')) as { words: { page: number; text: string }[] };
  const pages = new Map<number, unknown[]>();
  for (const word of corpus.words) {
    if (!Number.isInteger(word.page) || word.page < 1 || word.page > 604)
      throw new Error('Invalid Warsh source page');
    const words = pages.get(word.page) ?? [];
    words.push(word);
    pages.set(word.page, words);
  }
  const directory = 'assets/warsh-unicode';
  mkdirSync(path.join(root, directory), { recursive: true });
  copyFileSync(
    path.join(root, 'assets/fonts/UthmanicWarsh-v-3.0.LICENSE.txt'),
    path.join(root, directory, 'SOURCE-LICENSE.txt'),
  );
  const loaders = [
    '// Generated by scripts/prepare-reader-assets.ts. Quran text stays in lazy local assets.',
    'export const warshPageAssets: Record<number, () => number> = {',
  ];
  const hashes: Record<string, string> = {};
  const packagedPages: { name: string; json: string }[] = [];
  let total = 0;
  for (let page = 1; page <= 604; page++) {
    const value = { words: pages.get(page) };
    const validated = parseWarshMushafResponse(value, page, printedWarshPageAyahs(page));
    total += validated.length;
    const name = `page-${page}.quran`;
    // JSON repackaging only: every word's original codepoints and metadata survive.
    const json = JSON.stringify(value);
    hashes[name] = sha256(json);
    packagedPages.push({ name, json });
    loaders.push(`  ${page}: () => require('../../../${directory}/${name}') as number,`);
  }
  if (total !== corpus.words.length) throw new Error('Warsh source words were lost');
  // Reject an invalid full response before replacing any packaged Quran page.
  for (const { name, json } of packagedPages) write(`${directory}/${name}`, json);
  loaders.push('};', '');
  write('src/content/generated/warsh-page-assets.ts', loaders.join('\n'));
  write(
    `${directory}/provenance.json`,
    JSON.stringify(
      {
        sourceUrl,
        edition: 'warsh',
        signs: 'attached',
        acquired: '2026-11-14',
        sourceSha256: sha256(source),
        pages: 604,
        words: total,
        transformations:
          'Split JSON into pages only; no text normalization, correction, or lexical alignment.',
        sha256: hashes,
      },
      null,
      2,
    ) + '\n',
  );
  console.log(
    `Preserved 114 original surah illustrations and ${total} validated Warsh words on 604 pages.`,
  );
}
void prepareWarsh().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
