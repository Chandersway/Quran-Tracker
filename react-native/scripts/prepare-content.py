"""Repackage the checked-in Kotlin assets without editing source text or imports.

Run from any working directory. Provenance includes hashes of every source input.
The original acquisition/import scripts remain unchanged in ../scripts.
"""
import hashlib
import json
import pathlib
import re
import shutil
import sqlite3

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'app/src/main/assets'
OUT = ROOT / 'src/content/generated'
OUT.mkdir(parents=True, exist_ok=True)
STUDY_OUT = ROOT / 'src/content/study-details'
STUDY_OUT.mkdir(parents=True, exist_ok=True)
hashes = {}

def source(path):
    file = SOURCE / path
    hashes[str(path)] = hashlib.sha256(file.read_bytes()).hexdigest()
    return file

def load(path):
    return json.loads(source(path).read_text(encoding='utf-8'))

def write(name, data):
    (OUT / name).write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')

metadata_source = ROOT.parent / 'app/src/main/java/com/Ameender/qurantracker/ui/SurahScreen.kt'
metadata = re.findall(r'Surah\(\s*(\d+),\s*"([^"]+)",\s*"([^"]+)",\s*(\d+),\s*(\d+)\)', metadata_source.read_text(encoding='utf-8'))
assert len(metadata) == 114, 'Source chapter metadata must contain all 114 surahs'
db = sqlite3.connect(source('Quraan.db'))
db.row_factory = sqlite3.Row
glyphs = sqlite3.connect(source('hafs_ayahinfo_1260.db'))
pages = {(s, a): p for s, a, p in glyphs.execute('SELECT sura_number,ayah_number,MIN(page_number) FROM glyphs GROUP BY sura_number,ayah_number')}
translations = {lang: {(r['surah'], r['ayah']): r['text'] for r in load(f'translations/{name}.json')} for lang, name in [('en', 'en_sahih'), ('nl', 'nl_siregar')]}
chapters = []
for raw_id, name, name_ar, count, juz in metadata:
    surah = int(raw_id)
    rows = db.execute('SELECT AYA_num, AYA FROM "ALL" WHERE SURA_num=? ORDER BY AYA_num', (surah,)).fetchall()
    assert len(rows) == int(count), f'Unexpected ayah count in {surah}'
    words = {r['ayah']: r for r in load(f'word_by_word_surah_{surah}.json')}
    content = []
    study = []
    for row in rows:
        ayah = row['AYA_num']
        details = words.get(ayah, {})
        content.append({'number': ayah, 'text': row['AYA'], 'page': pages.get((surah, ayah), 1), 'en': translations['en'].get((surah, ayah), ''), 'nl': translations['nl'].get((surah, ayah), '')})
        study.append({'number': ayah, 'words': details.get('words', []), 'irab': details.get('e3rab', '')})
    write(f'surah-{surah}.json', content)
    (STUDY_OUT / f'surah-{surah}.quran').write_text(json.dumps(study, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    chapters.append({'id': surah, 'name': name, 'nameAr': name_ar, 'verseCount': int(count), 'juz': int(juz), 'page': content[0]['page']})
write('chapters.json', chapters)
assert sum(c['verseCount'] for c in chapters) == 6236
for asset in ['rub_starts.json', 'warsh_rub_starts.json', 'warsh_ayah_map.json', 'warsh_maknoon_positions.json', 'mutashabiha_data.json']:
    shutil.copyfile(source(asset), OUT / asset)
for asset in ['rub_starts.LICENSE.txt', 'warsh_ayah_map.LICENSE.txt']:
    shutil.copyfile(source(asset), OUT / asset)
# Keep a standalone immutable books database for the native reader adapter.
assets_out = ROOT / 'assets'
assets_out.mkdir(exist_ok=True)
shutil.copyfile(source('books/books.db'), assets_out / 'books.db')
shutil.copyfile(source('Quraan.db'), assets_out / 'Quraan.db')
write('provenance.json', {'source': 'Sibling Kotlin assets; original bytes and import scripts unchanged', 'surahs': 114, 'ayahs': 6236, 'sha256': hashes})
loader = ['// Generated by scripts/prepare-content.py. Do not hand edit.', 'import type { Ayah } from "../types";', 'export const surahLoaders: Record<number, () => Ayah[]> = {']
loader += [f'  {i}: () => require("./surah-{i}.json") as Ayah[],' for i in range(1, 115)]
loader += ['};', '']
(OUT / 'loaders.ts').write_text('\n'.join(loader), encoding='utf-8')
study_loader = ['// Generated by scripts/prepare-content.py. Do not hand edit.', 'export const studyAssetLoaders: Record<number, () => number> = {']
study_loader += [f'  {i}: () => require("../study-details/surah-{i}.quran") as number,' for i in range(1, 115)]
study_loader += ['};', '']
(OUT / 'study-loaders.ts').write_text('\n'.join(study_loader), encoding='utf-8')
print(f'Prepared {len(chapters)} surahs / 6,236 ayahs, lightweight text/translations, async study details, divisions and original book database.')

audio_dir = ROOT / 'src/content/audio'
audio_loader = ['// Generated by scripts/prepare-content.py. Audio metadata stays in offline local assets.', '/* eslint @typescript-eslint/no-require-imports: off */', 'export const audioAssetLoaders: Record<number, () => number> = {']
for surah in range(1, 115):
    asset = audio_dir / f'surah_{surah}.quran'
    assert asset.is_file(), f'Missing bundled audio catalog: {asset}'
    audio_loader.append(f'  {surah}: () => require("./audio/surah_{surah}.quran") as number,')
audio_loader.extend(['};', '', 'export function loadAudioCatalogAsset(surah: number): number {', '  const loader = audioAssetLoaders[surah];', '  if (!loader) throw new RangeError("Surah must be between 1 and 114");', '  return loader();', '}', ''])
(ROOT / 'src/content/audioCatalog.ts').write_text('\n'.join(audio_loader), encoding='utf-8')

# Original printed pages and coordinate systems are retained, not approximated.
page_dir = ROOT / 'assets/mushaf'
page_dir.mkdir(parents=True, exist_ok=True)
page_loader = ['// Generated from original Kotlin image resources.', 'import type { ImageSourcePropType } from "react-native";', "export const printedPages: Record<'hafs' | 'muhammadi', Record<number, ImageSourcePropType>> = {"]
reader_source = (ROOT.parent / 'app/src/main/java/com/Ameender/qurantracker/ui/QuranReaderScreen.kt').read_text(encoding='utf-8')
page_ranges = {}
for edition, prefix, count, method in [('hafs', 'hafs_madina_page', 604, 'hafsMadinaPagesForSurah'), ('muhammadi', 'warsh_page', 638, 'warshPagesForSurah')]:
    page_loader.append(f'  {edition}: {{')
    for page in range(1, count + 1):
        name = f'{prefix}_{page:03}.png'
        shutil.copyfile(ROOT.parent / 'app/src/main/res/drawable' / name, page_dir / name)
        page_loader.append(f'    {page}: require("../../../assets/mushaf/{name}"),')
    page_loader.append('  },')
    block = reader_source.split(f'fun {method}(')[1].split('else -> IntRange.EMPTY')[0]
    page_ranges[edition] = {number: [int(start), int(end)] for number, start, end in re.findall(r'(\d+)\s*->\s*(\d+)\.\.(\d+)', block)}
page_loader.append('};\n')
(OUT / 'printedPages.ts').write_text('\n'.join(page_loader), encoding='utf-8')
write('page-ranges.json', page_ranges)
positions = {}
for row in glyphs.execute('SELECT page_number,sura_number,ayah_number,line_number,MIN(min_x),MIN(min_y),MAX(max_x),MAX(max_y) FROM glyphs GROUP BY page_number,sura_number,ayah_number,line_number ORDER BY page_number,sura_number,ayah_number,line_number'):
    page, surah, ayah, line, x1, y1, x2, y2 = row
    positions.setdefault(str(page), []).append([surah, ayah, round(x1 / 1260, 7), round(y1 / 1834, 7), round((x2-x1) / 1260, 7), round((y2-y1) / 1834, 7)])
write('hafs-positions.json', positions)
# The legacy Muhammadi coordinate JS is data only; evaluate no source code.
coordinate_text = source('coordinate_muhammadi.js').read_text(encoding='utf-8')
coordinate_match = re.search(r'(\[.*\])', coordinate_text, re.S)
if coordinate_match:
    try:
        write('muhammadi-positions.json', json.loads(coordinate_match.group(1)))
    except json.JSONDecodeError:
        pass
print('Prepared all 1,242 original printed pages and Hafs hit-test geometry.')
write('provenance.json', {'source': 'Sibling Kotlin assets; original bytes and import scripts unchanged', 'surahs': 114, 'ayahs': 6236, 'sha256': hashes})
