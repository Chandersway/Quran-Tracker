// Helper: geef HizbInfo voor een bepaald hizb nummer
fun getHizbInfo(hizbNumber: Int): HizbInfo? =
    ALL_HIZB.find { it.hizbNumber == hizbNumber }

// Helper: geef alle hizb voor een bepaalde juz
// Juz 1 = Hizb 1-2, Juz 2 = Hizb 3-4, etc.
fun getHizbForJuz(juzNumber: Int): List<HizbInfo> {
    val hizbStart = (juzNumber - 1) * 2 + 1
    val hizbEnd   = juzNumber * 2
    return ALL_HIZB.filter { it.hizbNumber in hizbStart..hizbEnd }
}
